void loop() {
    static uint8_t channel = 1;
    static unsigned long last_hop = 0;

    if (millis() - last_hop > 250) {
        last_hop = millis();
        channel = (channel % 13) + 1;
        esp_wifi_set_channel(channel, WIFI_SECOND_CHAN_NONE);
    }
}